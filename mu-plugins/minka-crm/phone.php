<?php
/**
 * Нормализация телефона в E.164.
 *
 * Нужна дважды: как ключ дедупликации лидов в EspoCRM и как основа хэша `ph`
 * для Meta — там номер должен быть в международном формате, иначе совпадение
 * с профилем не находится.
 */

defined( 'ABSPATH' ) || exit;

/**
 * Национальный номер Беларуси — ровно девять цифр.
 *
 * Мобильные коды: 25, 29, 33, 44. Городские начинаются с 1 или 2 (17 Минск,
 * 152 Гродно, 162 Брест, 212 Витебск, 222 Могилёв, 232 Гомель). Полный
 * справочник кодов в коде держать незачем: от потерянной цифры — а это самая
 * частая ошибка при вводе — защищает проверка длины.
 *
 * @param string $digits Только цифры, без кода страны.
 * @return bool
 */
function minka_crm_is_by_national( $digits ) {
	if ( 9 !== strlen( $digits ) ) {
		return false;
	}

	if ( in_array( substr( $digits, 0, 2 ), array( '25', '29', '33', '44' ), true ) ) {
		return true;
	}

	return (bool) preg_match( '/^[12]/', $digits );
}

/**
 * Национальная часть белорусского номера из любой местной записи.
 *
 * Понимает +375…, 375…, 8 0XX…, 0XX… и просто девять цифр.
 *
 * Отдельно снимается лишний код страны: поле на сайте подставляет «+375 »,
 * и номер, вставленный из буфера поверх подсказки, приезжает как «375375…»
 * или «375 8029…». Раньше такая заявка отклонялась, хотя номер был верный.
 *
 * Возвращает false, только если номер вообще не белорусский, — тогда его
 * разбирает вызывающий код. Если код страны белорусский, возвращается то,
 * что нашлось, даже неверной длины: такой номер должен быть отклонён, а не
 * уйти в общую международную ветку.
 *
 * @param string $raw Номер как его ввёл пользователь.
 * @return string|false Национальная часть или false.
 */
function minka_crm_by_national( $raw ) {
	$plus   = ( strpos( trim( (string) $raw ), '+' ) === 0 );
	$digits = preg_replace( '/\D+/', '', (string) $raw );

	$had_country_code = false;

	// Пока под кодом страны остаётся больше девяти цифр — код лишний.
	while ( 0 === strpos( $digits, '375' ) && strlen( $digits ) > 12 ) {
		$digits           = substr( $digits, 3 );
		$had_country_code = true;
	}

	if ( 0 === strpos( $digits, '375' ) ) {
		return substr( $digits, 3 );
	}

	// Номер с плюсом и чужим кодом страны белорусским не считаем: +7, +48…
	if ( $plus && ! $had_country_code ) {
		return false;
	}

	if ( 11 === strlen( $digits ) && '80' === substr( $digits, 0, 2 ) ) {
		return substr( $digits, 2 );
	}

	if ( 10 === strlen( $digits ) && '0' === substr( $digits, 0, 1 ) ) {
		return substr( $digits, 1 );
	}

	if ( 9 === strlen( $digits ) ) {
		return $digits;
	}

	// Код страны был, а цифр под ним не девять — номер белорусский и битый.
	return $had_country_code ? $digits : false;
}

/**
 * Приводит номер к виду +375291112233.
 *
 * Возвращает пустую строку, если распознать номер не удалось: лучше оставить
 * поле пустым, чем записать мусор, по которому потом склеятся разные люди.
 *
 * @param string $raw Номер как его ввёл пользователь.
 * @return string
 */
function minka_crm_normalize_phone( $raw ) {
	$raw = (string) $raw;

	$plus   = ( strpos( trim( $raw ), '+' ) === 0 );
	$digits = preg_replace( '/\D+/', '', $raw );

	if ( '' === $digits ) {
		return '';
	}

	// Беларусь разбираем первой и строго: любая местная запись сводится к девяти
	// цифрам, и если их не девять — номер не принимается. Раньше ветка для
	// международной записи пропускала +375 с любой длиной, и номер с потерянной
	// цифрой уходил в CRM как настоящий.
	$national = minka_crm_by_national( $raw );

	if ( false !== $national ) {
		return minka_crm_is_by_national( $national ) ? '+375' . $national : '';
	}

	// Уже международный: +7..., +48...
	// Длина проверяется по E.164: меньше восьми или больше пятнадцати цифр —
	// это заведомо не номер, и отправлять его в CRM смысла нет.
	if ( $plus ) {
		$length = strlen( $digits );

		if ( $length < 8 || $length > 15 ) {
			return '';
		}

		return '+' . $digits;
	}

	// Местная запись через 8: в России это 8 9XX (белорусская 8 0XX разобрана выше).
	if ( 11 === strlen( $digits ) && '8' === $digits[0] ) {
		return '+7' . substr( $digits, 1 );
	}

	// 79991112233
	if ( 11 === strlen( $digits ) && '7' === $digits[0] ) {
		return '+' . $digits;
	}

	return '';
}
