/**
 * Создаёт статьи, которых ещё нет.
 *
 * В два прохода: сначала все записи, потом содержимое. Иначе ссылки между
 * новыми статьями вели бы в блог — на момент создания первой остальных
 * ещё не существует.
 */
function minka_seed_blog_posts() {
	if ( ! function_exists( 'update_field' ) ) {
		return;
	}

	if ( (int) get_option( 'minka_blog_seeded_version' ) >= MINKA_BLOG_SEED_VERSION ) {
		return;
	}

	update_option( 'minka_blog_seeded_version', MINKA_BLOG_SEED_VERSION );

	$created = array();

	foreach ( minka_blog_seed_articles() as $article ) {
		// Статья с таким адресом уже есть — не трогаем: её мог править человек.
		if ( get_page_by_path( $article['slug'], OBJECT, 'post' ) ) {
			continue;
		}

		$id = wp_insert_post(
			array(
				'post_type'    => 'post',
				'post_status'  => 'publish',
				'post_title'   => $article['title'],
				'post_name'    => $article['slug'],
				'post_excerpt' => $article['excerpt'],
				'post_date'    => $article['date'],
				'post_content' => '',
			)
		);

		if ( ! $id || is_wp_error( $id ) ) {
			continue;
		}

		$created[ $id ] = $article;
	}

	foreach ( $created as $id => $article ) {
		$blocks = $article['blocks'];

		array_walk_recursive(
			$blocks,
			function ( &$value ) {
				if ( is_string( $value ) ) {
					$value = minka_blog_seed_resolve( $value );
				}
			}
		);

		update_field( 'field_minka_post_blocks', $blocks, $id );

		$faq = array();

		foreach ( $article['faq'] as $row ) {
			$faq[] = array(
				'faq_question' => $row[0],
				'faq_answer'   => minka_blog_seed_resolve( $row[1] ),
			);
		}

		// Свои вопросы вместо общих для блога: они попадают и в разметку FAQPage.
		update_field( 'field_minka_post_faq_inherit', 0, $id );
		update_field( 'field_minka_post_faq', $faq, $id );

		$cover = minka_blog_seed_attachment( $article['cover'] );

		if ( $cover ) {
			set_post_thumbnail( $id, $cover );
		}

		update_post_meta( $id, '_yoast_wpseo_title', $article['seo']['title'] );
		update_post_meta( $id, '_yoast_wpseo_metadesc', $article['seo']['metadesc'] );
		update_post_meta( $id, '_yoast_wpseo_focuskw', $article['seo']['focuskw'] );
		update_post_meta( $id, '_yoast_wpseo_opengraph-title', $article['seo']['og_title'] );
		update_post_meta( $id, '_yoast_wpseo_opengraph-description', $article['seo']['og_desc'] );
		update_post_meta( $id, '_yoast_wpseo_twitter-title', $article['seo']['og_title'] );
		update_post_meta( $id, '_yoast_wpseo_twitter-description', $article['seo']['og_desc'] );

		$og = minka_blog_seed_attachment( $article['og'] );

		if ( $og ) {
			update_post_meta( $id, '_yoast_wpseo_opengraph-image', wp_get_attachment_image_url( $og, 'full' ) );
			// Строкой: число Yoast отбрасывает при сохранении мета-полей.
			update_post_meta( $id, '_yoast_wpseo_opengraph-image-id', (string) $og );
		}
	}
}
add_action( 'admin_init', 'minka_seed_blog_posts', 25 );
