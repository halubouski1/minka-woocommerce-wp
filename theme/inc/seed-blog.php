/**
 * Подставляет в текст настоящие адреса страниц.
 *
 * %CATALOG%, %CONTACTS%, %CARE%, %BLOG% — страницы сайта.
 * %POST:слаг% — другая статья блога. Если её ещё нет, ссылка ведёт в блог:
 * битой она не будет ни при каком порядке создания записей.
 */
function minka_blog_seed_resolve( $html ) {
	$html = strtr(
		$html,
		array(
			'%CATALOG%'  => minka_page_url( 'catalog' ),
			'%CONTACTS%' => minka_page_url( 'contacts' ),
			'%CARE%'     => minka_page_url( 'care' ),
			'%BLOG%'     => minka_page_url( 'blog' ),
		)
	);

	return preg_replace_callback(
		'/%POST:([a-z0-9-]+)%/',
		function ( $matches ) {
			$post = get_page_by_path( $matches[1], OBJECT, 'post' );

			return $post ? get_permalink( $post ) : minka_page_url( 'blog' );
		},
		$html
	);
}

/**
 * Ищет картинку в медиатеке по имени файла.
 *
 * По имени, а не по ID: на локальном сайте и на хостинге у одной и той же
 * фотографии разные идентификаторы, а имя файла совпадает.
 */
function minka_blog_seed_attachment( $file ) {
	global $wpdb;

	$id = $wpdb->get_var(
		$wpdb->prepare(
			"SELECT post_id FROM {$wpdb->postmeta} WHERE meta_key = '_wp_attached_file' AND meta_value LIKE %s ORDER BY post_id ASC LIMIT 1",
			'%' . $wpdb->esc_like( $file )
		)
	);

	return (int) $id;
}

